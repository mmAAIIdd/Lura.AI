/**
 * Владелец рабочего пространства — кто именно, в виде проверенного значения.
 *
 * Файл намеренно без единого импорта. Его тянет за собой и auth.ts, и слой
 * хранилища; общий импорт между ними замкнул бы цикл, а любой node:-модуль
 * закрыл бы дорогу в edge-рантайм middleware. Здесь нет ничего, кроме правила
 * и проверки, — и не должно появиться.
 */

/** Владелец локальной разработки и открытого режима. Разбор — в auth.ts. */
export const LOCAL_OWNER_VALUE = "local";

/**
 * Идентификатор владельца, прошедший проверку.
 *
 * Тип помеченный: обычная строка в него не присваивается. Из-за этого
 * studioStore() нельзя позвать с чем попало — например, с идентификатором
 * документа или с сырым sub из токена, — и проверка перестаёт быть тем, о чём
 * нужно помнить.
 */
export type OwnerId = string & { readonly __ownerId: unique symbol };

/**
 * Проверка идентификатора владельца. Не подошёл — null, и вызывающий отказывает.
 *
 * Регистр НЕ приводится. Соблазн сделать toLowerCase() здесь велик, но это
 * ровно тот способ склеить двух разных владельцев в одного: если внешняя
 * система когда-нибудь выдаст «AB» и «ab» как разные субъекты, тихое
 * приведение регистра сведёт их в одно пространство и покажет документы одного
 * другому. Утечка, которой не было бы без «удобства». Поэтому не-строчная
 * буква — это отказ, а не повод чинить значение за того, кто его прислал.
 *
 * Набор символов сужен до тех, что безопасны и как имя папки на диске, и как
 * значение в SQL: ни точки, ни слэша, ни пробела — путь ..\..\ в такой
 * идентификатор не записывается в принципе.
 */
export function asOwnerId(raw: string): OwnerId | null {
  const value = raw.trim();
  if (value !== value.toLowerCase()) return null;
  if (!/^[a-z0-9_-]{1,64}$/.test(value)) return null;
  return value as OwnerId;
}

/** Тот же «local», уже помеченный: литерал заведомо проходит проверку выше. */
export const LOCAL_OWNER: OwnerId = LOCAL_OWNER_VALUE as OwnerId;
