/**
 * Сборка списка классов.
 *
 * Шаблонная строка вида `st ${open ? "" : "no-panel"}` оставляет за собой
 * висячий пробел, и в разметке появляется class="st ". Само по себе это не
 * ломает ничего, но в отчёте о расхождении разметки такая строка выглядит
 * отличием от class="st" — и настоящую причину в этом diff уже не найти.
 */
export function cx(...parts: (string | false | null | undefined)[]): string {
  return parts.filter(Boolean).join(" ");
}
